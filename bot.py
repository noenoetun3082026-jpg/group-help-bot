# CHOOSE REPLY
# ============================================================

def choose_reply(items, chat_id):
    if not items:
        return None

    old = LAST_REPLY.get(chat_id)

    choices = [
        item for item in items
        if item != old
    ]

    if not choices:
        choices = items

    result = random.choice(choices)

    LAST_REPLY[chat_id] = result

    return result


# ============================================================
# CUSTOM REPLIES
# ============================================================

def custom_response(text, chat_id):

    lowered = text.strip().lower()

    for keyword, value in replies.items():

        if keyword.lower() in lowered:

            if isinstance(value, list):
                return choose_reply(
                    value,
                    chat_id
                )

            return value

    return None


# ============================================================
# MAKE RESPONSE
# ============================================================

def make_response(text, chat_id):

    text = text.strip()
    lowered = text.lower()

    # Custom reply first
    custom = custom_response(
        text,
        chat_id
    )

    if custom:
        return custom

    # Question
    if any(word in lowered for word in [
        "ဘာလဲ",
        "ဘာလို့",
        "ဘယ်လို",
        "ဘယ်မှာ",
        "ဘယ်သူ",
        "ဘာလုပ်",
        "?",
        "လား",
    ]):
        return choose_reply(
            QUESTION_REPLIES,
            chat_id
        )

    # Greeting
    if any(word in lowered for word in [
        "ဟယ်လို",
        "ဟလို",
        "မင်္ဂလာပါ",
        "hello",
        "hi",
    ]):
        return choose_reply(
            GREETING_REPLIES,
            chat_id
        )

    # Noe
    if any(word in lowered for word in [
        "နိုး",
        "noe",
    ]):
        return choose_reply(
            NOE_REPLIES,
            chat_id
        )

    # New
    if "နယူး" in lowered:
        return choose_reply(
            [
                "မပျင်းအောင် စကားလေးဝင်ပြောနော်",
                "စကားဝင်ပြောလေ",
                "ဒီမှာရှိတယ်",
                "မပျင်းနဲ့",
                "ဆက်ပြောလေ",
                "အင်း ပြောကြ",
                "ငြိမ်မနေနဲ့",
            ],
            chat_id
        )

    # Take
    if any(word in lowered for word in [
        "ယူလိုက်ပါလား",
        "ယူမလား",
        "ယူလိုက်",
        "ယူပါ",
    ]):
        return choose_reply(
            TAKE_REPLIES,
            chat_id
        )

    # Teasing
    if any(word in lowered for word in [
        "ရမ်း",
        "စတာ",
        "စ",
        "ဟာ",
        "ဟေ့",
        "အမယ်",
        "နောက်တာ",
    ]):
        if random.random() < 0.85:
            return choose_reply(
                TEASE_REPLIES,
                chat_id
            )

    # Dot command
    if text.startswith("."):
        return choose_reply(
            COMMAND_REPLIES,
            chat_id
        )

    # Very short text
    if len(text) <= 2:
        return choose_reply(
            SHORT_REPLIES,
            chat_id
        )

    # Normal conversation
    if random.random() < SPONTANEOUS_CHANCE:
        return choose_reply(
            NORMAL_REPLIES,
            chat_id
        )

    return None


