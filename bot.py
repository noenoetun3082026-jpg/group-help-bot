async def register_group(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):

    chat = update.effective_chat

    if not chat:
        return

    if not await is_admin(
        update,
        context
    ):
        return

    groups[str(chat.id)] = {
        "id": chat.id,
        "title": chat.title or "",
        "username": chat.username or "",
    }

    save_json(
        GROUPS_FILE,
        groups
    )

    await update.message.reply_text(
        "ဒီ Group ကို မှတ်ထားလိုက်ပြီ။"
    )


