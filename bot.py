# GROUPS
# ============================================================

async def groups_command(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):

    if not groups:

        await update.message.reply_text(
            "Group မရှိသေးဘူး။"
        )

        return

    lines = ["Groups:"]

    for data in groups.values():

        title = data.get(
            "title",
            ""
        )

        username = data.get(
            "username",
            ""
        )

        if username:
            lines.append(
                f"{title} @{username}"
            )
        else:
            lines.append(title)

    await update.message.reply_text(
        "\n".join(lines)
    )


